async def main():
    async with AsyncSessionLocal() as db:
        entries = (
            await db.execute(select(VocabEntries).where(VocabEntries.cefr_level == 'A1'))
        ).scalars().all()
        by_source_key = {e.source_key: e for e in entries}

        updated = 0
        missing = []
        for idx, (ru, tg) in enumerate(TRANSLATIONS):
            key = f'seed:A1:vocab:{idx}'
            entry = by_source_key.get(key)
            if entry is None:
                missing.append(key)
                continue
            entry.translation_ru = ru
            entry.translation_tg = tg
            updated += 1

        await db.commit()
        print(f'updated {updated} / {len(entries)} A1 vocab entries')
        if missing:
            print('missing source_keys:', missing[:20], '...' if len(missing) > 20 else '')


asyncio.run(main())
